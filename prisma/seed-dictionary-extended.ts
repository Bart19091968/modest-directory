async function main() {
  console.log(`Seeding ${terms.length} dictionary terms...`)
  let upserted = 0

  for (const t of terms) {
    const cat = normalizeCategory[t.category] ?? t.category
    await prisma.dictionaryTerm.upsert({
      where: { slug: t.slug },
      update: {
        term: t.term,
        arabic: t.arabic ?? null,
        pronunciation: t.pronunciation ?? null,
        shortDefinition: t.shortDef,
        longDefinition: t.longDef,
        category: cat,
        aliases: splitArr(t.aliases),
        transliterationVariants: splitArr(t.variants),
        relatedTermSlugs: splitArr(t.relatedSlugs),
        relatedCategoryLinks: deriveLinks(t.dirLinks, 'category'),
        relatedBlogLinks: deriveLinks(t.blogLinks, 'blog'),
        seoTitle: t.seoTitle ?? null,
        seoDescription: t.seoDesc ?? null,
        isPublished: true,
      },
      create: {
        term: t.term,
        slug: t.slug,
        arabic: t.arabic ?? null,
        pronunciation: t.pronunciation ?? null,
        shortDefinition: t.shortDef,
        longDefinition: t.longDef,
        category: cat,
        aliases: splitArr(t.aliases),
        transliterationVariants: splitArr(t.variants),
        relatedTermSlugs: splitArr(t.relatedSlugs),
        relatedCategoryLinks: deriveLinks(t.dirLinks, 'category'),
        relatedBlogLinks: deriveLinks(t.blogLinks, 'blog'),
        seoTitle: t.seoTitle ?? null,
        seoDescription: t.seoDesc ?? null,
        isPublished: true,
      },
    })
    upserted++
    if (upserted % 10 === 0) console.log(`  ${upserted}/${terms.length}`)
  }

  console.log(`Done. Upserted ${upserted} terms.`)
}

main()
  .catch(e => { console.error(e); process.exit(1) })
  .finally(() => prisma.$disconnect())
